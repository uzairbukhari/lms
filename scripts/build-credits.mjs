// Builds apps/web/public/credits.html: the parent-facing page that thanks photographers and carries the Oak licence line.
// Reads content/media/manifest.json and content/sources/*.json. Run after adding media or Oak provenance: node scripts/build-credits.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const read = (p) => JSON.parse(readFileSync(new URL(`../${p}`, import.meta.url), "utf8"));
const esc = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
import { loadManifest } from "./media-manifest.mjs";
const manifest = loadManifest();
const photos = manifest.filter((f) => f.source === "unsplash");
const diagrams = manifest.filter((f) => f.source === "coteach");
const sourcesDir = new URL("../content/sources/", import.meta.url);
const sources = existsSync(sourcesDir) ? readdirSync(sourcesDir).filter((f) => f.endsWith(".json")).map((f) => ({ slug: f.replace(".json", ""), ...JSON.parse(readFileSync(new URL(f, sourcesDir), "utf8")) })) : [];

const oakLines = sources.flatMap((s) => (s.lessons ?? []).map((l) => `<li>${esc(s.slug)}: <a href="${esc(l.url)}" rel="noopener">${esc(l.title)}</a></li>`));
const html = `<!doctype html>
<html lang="en-GB">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="robots" content="noindex"><title>Credits</title>
<style>body{font-family:system-ui,sans-serif;max-width:46rem;margin:2rem auto;padding:0 1rem;line-height:1.5;color:#1b1e3a;background:#fffdf7}a{color:#2a4bd7}h1,h2{line-height:1.2}li{margin:.25rem 0}small{color:#555}</style></head>
<body>
<h1>Credits</h1>
<p>This page is for parents. It thanks the people whose work helps the lessons.</p>
<h2>Oak National Academy</h2>
<p>Lessons are adapted from the structure, key words and common mistakes in Oak National Academy's curriculum. They are not copies, and Oak did not make or approve them.</p>
<p><strong>Contains public sector information licensed under the Open Government Licence v3.0.</strong></p>
${oakLines.length ? `<details><summary>Oak lessons we used (${oakLines.length})</summary><ul>${oakLines.join("")}</ul></details>` : ""}
<h2>Photos from Unsplash (${photos.length})</h2>
${photos.length ? `<ul>${photos.map((p) => `<li>${esc(p.alt)} &ndash; Photo by <a href="${esc(p.author_url)}" rel="noopener">${esc(p.author)}</a> on <a href="${esc(p.source_url)}" rel="noopener">Unsplash</a></li>`).join("")}</ul>` : "<p>No photos yet.</p>"}
<h2>Maths diagrams from Coteach (${diagrams.length})</h2>
<p>${diagrams.length ? `${diagrams.length} diagrams made with Coteach.` : "No diagrams yet."}</p>
<h2>Made for these lessons</h2>
<p>The narrated clips and their posters are made for these lessons. Celebration animations were designed with ideas from AnimatedWebs and written for this app.</p>
<p><small>Generated by scripts/build-credits.mjs. Do not edit by hand.</small></p>
</body></html>
`;
writeFileSync(new URL("../apps/web/public/credits.html", import.meta.url), html);
console.log(`credits.html: ${photos.length} photos, ${diagrams.length} diagrams, ${oakLines.length} Oak lessons`);
