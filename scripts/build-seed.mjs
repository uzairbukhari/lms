// Builds content/seed/week1.sql and week2.sql: classes, calendar, courses, that week's lessons (with quizzes) and assignments.
// Contains no personal data (no student names or passwords). Safe to re-run: ids are deterministic and every insert is
// INSERT OR IGNORE, so applying the SQL twice changes nothing.
//   node scripts/build-seed.mjs            writes content/seed/week1.sql (diag-* lessons) and week2.sql (w2-* lessons)
// Apply: cd worker && npx wrangler d1 execute lms-db --remote --file ../content/seed/week2.sql
// New lessons are inserted only if their id does not exist yet. A lesson that is already live is NOT changed by this
// file: publish a rebuilt lesson as a new version through the admin importer (Lessons, Import) instead.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const id = (key) => {
  const h = createHash("sha1").update(`lms-seed:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const insert = (table, row) => `INSERT OR IGNORE INTO ${table} (${Object.keys(row).join(", ")}) VALUES (${Object.values(row).map(q).join(", ")});`;

// School year: starts Monday 2 Nov 2026 (1 Nov is a Sunday); 12 teaching weeks + exam week per semester, 1-week break after each.
const START = "2026-11-02";
const DAY = 864e5;
const fmt = (ms) => new Date(ms).toISOString().slice(0, 10);
const terms = [];
let s = Date.parse(`${START}T00:00:00Z`);
for (let n = 1; n <= 4; n++) {
  const e = s + 13 * 7 * DAY - DAY;
  terms.push({ number: n, start: fmt(s), end: fmt(e) });
  s = e + DAY + 7 * DAY;
}
const DUE = "2026-11-08"; // Sunday of week 1

const classes = [
  { key: "class-1", name: "Class 1", description: "Age 7 to 8" },
  { key: "class-4", name: "Class 4", description: "Age 9 to 10" },
];
const SUBJECT_TITLE = { maths: "Maths", science: "Science", "data-ai": "Computer Science, Data & AI", "general-knowledge": "General Knowledge", english: "English" };

const WEEKS = [
  { week: 1, prefix: "diag-" },
  { week: 2, prefix: "w2-" },
];
const dir = join(root, "content/lessons");

for (const { week, prefix } of WEEKS) {
const out = ["-- Generated by scripts/build-seed.mjs. Do not edit by hand.", "PRAGMA foreign_keys = ON;"];

for (const c of classes) {
  out.push(insert("classes", { id: id(c.key), name: c.name, description: c.description, visibility_mode: "released" }));
  for (const t of terms) {
    out.push(insert("terms", { id: id(`${c.key}:term:${t.number}`), class_id: id(c.key), number: t.number, name: `Semester ${t.number}`, start_date: t.start, end_date: t.end, teaching_weeks: 12, exam_week: 13 }));
  }
}

const files = readdirSync(dir).filter((f) => f.startsWith(prefix) && f.endsWith(".json")).sort();
const seenCourses = new Set();
let order = (week - 1) * 100;
for (const f of files) {
  const file = JSON.parse(readFileSync(join(dir, f), "utf8"));
  const { lesson, blocks, quiz } = file;
  const cls = lesson.curriculum.course.match(/class-(\d)$/)[1];
  const classKey = `class-${cls}`;
  const courseId = id(`course:${lesson.curriculum.course}`);
  if (!seenCourses.has(courseId)) {
    seenCourses.add(courseId);
    out.push(insert("courses", { id: courseId, slug: lesson.curriculum.course, title: `${SUBJECT_TITLE[lesson.subject]} (Class ${cls})`, description: `${SUBJECT_TITLE[lesson.subject]} for Class ${cls}`, subject_id: lesson.subject, age_band: lesson.age_band, status: "published" }));
    out.push(insert("course_assignments", { id: id(`assign:${lesson.curriculum.course}:${classKey}`), course_id: courseId, class_id: id(classKey), due_date: DUE }));
  }
  const lessonId = id(`lesson:${lesson.slug}`);
  const quizId = id(`quiz:${lesson.slug}:1`);
  // The full lesson JSON is stored once (source_json); blocks and quiz rows are derived from it inside SQL to keep the file small.
  out.push(
    `WITH src(j) AS (VALUES (${q(JSON.stringify(file))})) INSERT OR IGNORE INTO lessons (id, slug, subject_id, title, summary, age_band, difficulty, estimated_minutes, unit, sort_order, status, current_version, content_json, source_json) ` +
      `SELECT ${q(lessonId)}, json_extract(j,'$.lesson.slug'), json_extract(j,'$.lesson.subject'), json_extract(j,'$.lesson.title'), json_extract(j,'$.lesson.summary'), json_extract(j,'$.lesson.age_band'), json_extract(j,'$.lesson.difficulty'), json_extract(j,'$.lesson.estimated_minutes'), json_extract(j,'$.lesson.unit'), ${++order}, 'published', 1, json_extract(j,'$.blocks'), j FROM src;`,
  );
  out.push(insert("course_lessons", { course_id: courseId, lesson_id: lessonId, position: 100 + week, semester: 1, week }));
  out.push(insert("quizzes", { id: quizId, kind: "lesson", lesson_id: lessonId, version: 1, is_current: 1, pass_percent: quiz.pass_percent, shuffle_questions: quiz.shuffle_questions ? 1 : 0, shuffle_options: quiz.shuffle_options ? 1 : 0, max_attempts: quiz.max_attempts ?? null }));
  const v = (path) => `json_extract(e.value,'$.${path}')`;
  out.push(
    `INSERT OR IGNORE INTO questions (id, quiz_id, ref, position, type, prompt, media_json, options_json, answer_json, hint, explanation, points, skill_tag) ` +
      `SELECT ${q(quizId)} || ':' || ${v("ref")}, ${q(quizId)}, ${v("ref")}, e.key + 1, ${v("type")}, ${v("prompt")}, ` +
      `CASE WHEN ${v("emoji")} IS NOT NULL THEN json_object('emoji', ${v("emoji")}) END, ` +
      `CASE ${v("type")} WHEN 'multiple_choice' THEN json_object('options', ${v("options")}) WHEN 'multi_select' THEN json_object('options', ${v("options")}) ` +
      `WHEN 'order' THEN json_object('items', ${v("items")}) WHEN 'match' THEN json_object('left', ${v("left")}, 'right', ${v("right")}) ` +
      `WHEN 'fill_blank' THEN json_object('text', ${v("text")}, 'blanks', ${v("blanks")}) WHEN 'hotspot' THEN json_object('scene', ${v("scene")}) WHEN 'slider' THEN json_object('range', ${v("range")}) ELSE 'null' END, ` +
      `${v("answer")}, ${v("hint")}, ${v("explanation")}, COALESCE(${v("points")}, 1), ${v("skill_tag")} ` +
      `FROM lessons l, json_each(l.source_json, '$.quiz.questions') e WHERE l.id = ${q(lessonId)};`,
  );
}
writeFileSync(join(root, `content/seed/week${week}.sql`), out.join("\n") + "\n");
console.log(`wrote content/seed/week${week}.sql (${out.length} statements, ${files.length} lessons)`);
}
